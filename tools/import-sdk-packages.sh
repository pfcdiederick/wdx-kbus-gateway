#!/usr/bin/env bash
# Fill ./sdk/include from the PREBUILT packages of a WAGO firmware SDK, without
# building the SDK (ptxdist). Only header files are taken; the libraries are
# loaded from the PFC at runtime.
#
#   tools/import-sdk-packages.sh <packages-dir>
#
# Example (PFC300 SDK, also fine for a PFC200, see README 2.2):
#   tools/import-sdk-packages.sh ~/Documents/WagoFirmware/pfc300-firmware-sdk/ptxproj/configs/wago-pfc300/packages
#
# Needed packages in <packages-dir>:
#   dal_<version>_<arch>.tgz                -> sdk/include/dal/*
#   libdbuskbuscommon_<version>_<arch>.tgz  -> sdk/include/ldkc_kbus_information.h
# The <arch> of the package does not matter: headers are source code and are
# compiled for the PFC by the Docker build.
set -euo pipefail

PKG=${1:?usage: $0 <packages-dir>}
DEST="$(cd "$(dirname "$0")/.." && pwd)/sdk/include"

dal=$(ls "$PKG"/dal_*.tgz 2>/dev/null | head -n1 || true)
info=$(ls "$PKG"/libdbuskbuscommon_*.tgz 2>/dev/null | head -n1 || true)
[[ -n "$dal" ]]  || { echo "no dal_*.tgz in $PKG" >&2; exit 1; }
[[ -n "$info" ]] || { echo "no libdbuskbuscommon_*.tgz in $PKG" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
tar xzf "$dal" -C "$tmp" usr/include
tar xzf "$info" -C "$tmp" usr/include/ldkc_kbus_information.h

rm -rf "$DEST"
mkdir -p "$DEST"
cp -a "$tmp/usr/include/dal" "$DEST/"
cp "$tmp/usr/include/ldkc_kbus_information.h" "$DEST/"

# <ldkc_kbus_information.h> includes <OsCommon.h> from WAGO's OsLinux library,
# which is not shipped as a package. It only needs these types and macros.
cat > "$DEST/OsCommon.h" <<'EOF'
// Minimal stand-in for WAGO's OsLinux <OsCommon.h>.
//
// Only the types and macros used by <ldkc_kbus_information.h> are defined.
// The real header is part of the WAGO OsLinux library of the PFC firmware SDK
// and can replace this file at any time.
// Generated by tools/import-sdk-packages.sh.
#ifndef KBUS_GW_OSCOMMON_SHIM_H
#define KBUS_GW_OSCOMMON_SHIM_H

#include <stdint.h>

typedef uint8_t  u8;
typedef uint16_t u16;
typedef uint32_t u32;
typedef int8_t   i8;
typedef int16_t  i16;
typedef int32_t  i32;

#define OS_PACKED_PRE
#define OS_PACKED_POST            __attribute__((packed))
#define OS_ARG_NONNULL(...)       __attribute__((nonnull __VA_ARGS__))
#define OS_WARN_UNUSED_RESULT     __attribute__((warn_unused_result))

#endif
EOF

echo "Imported headers into $DEST from:"
echo "  $(basename "$dal")"
echo "  $(basename "$info")"
echo
echo "Check that the DAL version matches the PFC (README 2.2):"
echo "  ssh root@<pfc-ip> ls -l /usr/lib/libdal.so*     -> libdal.so.$(basename "$dal" | sed -E 's/^dal_([0-9.]+)_.*/\1/')"
